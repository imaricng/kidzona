// Pomoćnik za pravilan oblik riječi "dijete" prema broju (hrvatska gramatika).
export function brojDjece(n: number): string {
  if (n === 1) return "1 dijete";
  if (n >= 2 && n <= 4) return `${n} djeteta`;
  return `${n} djece`;
}
